<script>
    function toggleFaq(btn) {
        const content = btn.nextElementSibling;
        const icon = btn.querySelector('.bi-chevron-down');
        const isHidden = content.classList.contains('hidden');
        
        // Close all other FAQ items for a neat accordion feel
        document.querySelectorAll('.faq-content').forEach(el => el.classList.add('hidden'));
        document.querySelectorAll('.faq-btn .bi-chevron-down').forEach(el => el.classList.remove('rotate-180'));

        if (isHidden) {
            content.classList.remove('hidden');
            icon.classList.add('rotate-180');
        }
    }
</script>
